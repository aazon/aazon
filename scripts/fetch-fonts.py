#!/usr/bin/env python3
"""Download latin/latin-ext woff2 subsets for the site fonts and emit a local @font-face sheet."""
import re
import subprocess
import sys
from pathlib import Path

UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
OUT_FONTS = Path(sys.argv[1])
OUT_CSS = Path(sys.argv[2])

REQUESTS = [
    ("Cardo", "https://fonts.googleapis.com/css2?family=Cardo:ital,wght@0,400;0,700;1,400&display=swap"),
    ("Fira Mono", "https://fonts.googleapis.com/css2?family=Fira+Mono:wght@400;700&display=swap"),
]

WANTED_SUBSETS = {"latin", "latin-ext"}

BLOCK_RE = re.compile(
    r"/\*\s*(?P<subset>[\w-]+)\s*\*/\s*@font-face\s*\{(?P<body>[^}]*)\}", re.S
)


def curl(url: str) -> bytes:
    return subprocess.run(
        ["curl", "-sSL", "--fail", "--max-time", "60", "-A", UA, url],
        check=True, capture_output=True,
    ).stdout


def field(body: str, name: str) -> str:
    m = re.search(rf"{name}\s*:\s*([^;]+);", body)
    return m.group(1).strip() if m else ""


OUT_FONTS.mkdir(parents=True, exist_ok=True)
faces = []

for family, css_url in REQUESTS:
    css = curl(css_url).decode()
    for m in BLOCK_RE.finditer(css):
        subset = m.group("subset")
        if subset not in WANTED_SUBSETS:
            continue
        body = m.group("body")
        style = field(body, "font-style") or "normal"
        weight = field(body, "font-weight") or "400"
        unicode_range = field(body, "unicode-range")
        src = re.search(r"url\((https://[^)]+\.woff2)\)", body).group(1)

        slug = family.lower().replace(" ", "-")
        italic = "-italic" if style == "italic" else ""
        filename = f"{slug}-{weight}{italic}-{subset}.woff2"
        (OUT_FONTS / filename).write_bytes(curl(src))

        faces.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            f"  font-style: {style};\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('/fonts/{filename}') format('woff2');\n"
            f"  unicode-range: {unicode_range};\n"
            "}"
        )
        print(f"  {filename}  ({(OUT_FONTS / filename).stat().st_size} bytes)")

header = (
    "/*\n"
    " * Self-hosted webfonts. Generated by scripts/fetch-fonts.py -- do not edit by hand.\n"
    " *\n"
    " * Cardo (Bembo-like Garalde serif) for prose, Fira Mono for code and UI chrome.\n"
    " * Both are self-hosted because the site's CSP restricts font-src to 'self'.\n"
    " *\n"
    " * Cardo: SIL Open Font License 1.1 (David J. Perry).\n"
    " * Fira Mono: SIL Open Font License 1.1 (Mozilla / Carrois / Edenspiekermann).\n"
    " */\n\n"
)
OUT_CSS.write_text(header + "\n\n".join(faces) + "\n")
print(f"wrote {OUT_CSS} with {len(faces)} @font-face rules")
